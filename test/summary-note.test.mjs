async function tempPaper() {
  const root = await mkdtemp(path.join(os.tmpdir(), 'lr-summary-'))
  const dir = path.join(root, 'paper-abc')
  await mkdir(dir, { recursive: true })
  return { root, dir }
}

const BODY = `# 均衡器笔记

> [!abstract] 速览
> 一句话：均衡补偿信道损耗。

## 1. 研究背景与问题

正文第一段，讨论 **信道损耗** 与 [p.3]。

## 2. 方法

方法段落。
`

test('readSummary returns empty state until the file exists', async () => {
  const { dir, root } = await tempPaper()
  try {
    const empty = await readSummary(dir)
    assert.equal(empty.markdown, '')
    assert.equal(empty.updatedAt, '')
    assert.equal(empty.version, summaryVersion(''))
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('writeSummary snapshots the previous body and reports a version', async () => {
  const { dir, root } = await tempPaper()
  try {
    const first = await writeSummary(dir, BODY)
    assert.equal(first.snapshot, '', 'nothing to snapshot on the first write')
    assert.equal(first.version, summaryVersion(BODY))
    assert.equal(await readFile(path.join(dir, 'summary.md'), 'utf8'), BODY)

    const second = await writeSummary(dir, `${BODY}\n补充一句。\n`, { source: 'revision', label: 'rev-1' })
    assert.match(second.snapshot, /^\d{8}-\d{6}-\d{3}(-\d+)?$/)
    const snapshotFile = path.join(dir, 'summary-history', `${second.snapshot}.md`)
    assert.equal(await readFile(snapshotFile, 'utf8'), BODY)

    // The written body always ends with a newline and normalises CRLF.
    await writeSummary(dir, 'abc\r\ndef')
    assert.equal(await readFile(path.join(dir, 'summary.md'), 'utf8'), 'abc\ndef\n')

    const read = await readSummary(dir)
    assert.equal(read.markdown, 'abc\ndef\n')
    assert.equal(read.version, summaryVersion('abc\ndef\n'))
    assert.ok(read.updatedAt)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('summaryVersion is the first 16 hex chars of the sha256', async () => {
  const digest = summaryVersion('hello')
  assert.match(digest, /^[0-9a-f]{16}$/)
  assert.notEqual(summaryVersion('hello'), summaryVersion('hello '))
  assert.equal(summaryVersion('hello'), summaryVersion('hello'))
})

test('history keeps the newest 30 snapshots and lists them newest first', async () => {
  const { dir, root } = await tempPaper()
  try {
    await writeSummary(dir, 'v0')
    for (let index = 1; index <= HISTORY_LIMIT + 4; index += 1) {
      await writeSummary(dir, `v${index}`)
    }
    const historyDir = path.join(dir, 'summary-history')
    const files = (await readdir(historyDir)).filter((name) => name.endsWith('.md'))
    assert.equal(files.length, HISTORY_LIMIT)

    const versions = await listHistory(dir)
    assert.equal(versions.length, HISTORY_LIMIT)
    for (const version of versions) {
      assert.match(version.stamp, /^\d{8}-\d{6}-\d{3}(-\d+)?$/)
      assert.ok(version.updatedAt)
      assert.ok(Number.isInteger(version.chars))
      assert.equal(typeof version.source, 'string')
    }
    // Newest first: the last snapshot holds the previous body, `v30`.
    const newest = versions[0]
    assert.equal(
      await readFile(path.join(historyDir, `${newest.stamp}.md`), 'utf8'),
      `v${HISTORY_LIMIT + 3}\n`,
    )

    const limited = await listHistory(dir, 3)
    assert.equal(limited.length, 3)
    assert.deepEqual(limited.map((item) => item.stamp), versions.slice(0, 3).map((item) => item.stamp))
    assert.deepEqual(await listHistory(path.join(root, 'missing'), 5), [])
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('history snapshots keep the origin of the body they contain', async () => {
  const { dir, root } = await tempPaper()
  try {
    // A note generated by the summary flow, then edited by hand, then revised.
    await writeSummary(dir, 'generated body', { source: 'summary' })
    await writeSummary(dir, 'manual body', { source: 'manual' })
    await writeSummary(dir, 'revised body', { source: 'revision' })

    const versions = await listHistory(dir)
    assert.equal(versions.length, 2)
    // Newest snapshot is the manual edit; the older one is the generated body.
    assert.equal(versions[0].source, 'manual')
    assert.equal(versions[1].source, 'summary')
    for (const version of versions) {
      assert.equal(typeof version.source, 'string')
      assert.ok(version.source.length > 0)
    }

    // Reading the snapshot sidecar directly confirms what was recorded: the
    // older snapshot must keep `summary`, never the source of the later write.
    const sidecar = JSON.parse(
      await readFile(path.join(dir, 'summary-history', `${versions[1].stamp}.json`), 'utf8'),
    )
    assert.equal(sidecar.source, 'summary')
    assert.ok(sidecar.updatedAt)

    // The current body's origin is tracked separately from the snapshots.
    const state = JSON.parse(await readFile(path.join(dir, 'summary-source.json'), 'utf8'))
    assert.equal(state.source, 'revision')

    // Restoring puts `restore` on the new current body while the snapshot of
    // the pre-restore body keeps its own origin.
    const restored = await restoreHistory(dir, versions[1].stamp)
    assert.equal(await readFile(path.join(dir, 'summary.md'), 'utf8'), 'generated body\n')
    const afterRestore = await listHistory(dir)
    assert.equal(afterRestore[0].source, 'revision')
    assert.equal(afterRestore[1].source, 'manual')
    const stateAfter = JSON.parse(await readFile(path.join(dir, 'summary-source.json'), 'utf8'))
    assert.equal(stateAfter.source, 'restore')
    assert.equal(restored.markdown, 'generated body\n')
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('history source labels stay renderable by the editor', async () => {
  const { dir, root } = await tempPaper()
  try {
    // The editor renders only manual/revision/restore/summary; `generate` is
    // what the summarizer passes, so it must be stored as `summary` or the row
    // silently falls back to "other".
    await writeSummary(dir, 'generated body', { source: 'generate' })
    await writeSummary(dir, 'manual body', { source: 'manual' })
    const versions = await listHistory(dir)
    // Only the first body has been snapshotted so far.
    assert.equal(versions.length, 1)
    assert.equal(versions[0].source, 'summary')

    const renderable = ['manual', 'revision', 'restore', 'summary']
    for (const version of versions) {
      assert.ok(renderable.includes(version.source), `unrenderable source: ${version.source}`)
    }

    // `revision` and `figures` are recorded verbatim; an unknown value is
    // passed through so the editor can still fall back to "other".
    await writeSummary(dir, 'a', { source: 'revision' })
    await writeSummary(dir, 'b', { source: 'figures' })
    const labeled = await listHistory(dir)
    assert.deepEqual(labeled.slice(0, 2).map((item) => item.source), ['revision', 'manual'])

    // Blank/missing source falls back to `manual` for the new body.
    await writeSummary(dir, 'c')
    assert.equal(JSON.parse(await readFile(path.join(dir, 'summary-source.json'), 'utf8')).source, 'manual')
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('history tolerates legacy snapshots without a sidecar', async () => {
  const { dir, root } = await tempPaper()
  try {
    const historyDir = path.join(dir, 'summary-history')
    await mkdir(historyDir, { recursive: true })
    await writeFile(path.join(historyDir, '20260101-120000-000.md'), 'legacy body\n')
    await writeFile(path.join(historyDir, '20260102-120000-000.md'), 'newer legacy\n')

    const versions = await listHistory(dir)
    assert.equal(versions.length, 2)
    // Newest first, and snapshots without a sidecar report an empty source
    // instead of throwing or inventing a label.
    assert.equal(versions[0].stamp, '20260102-120000-000')
    assert.equal(versions[1].stamp, '20260101-120000-000')
    for (const version of versions) {
      assert.equal(version.source, '')
      assert.ok(version.updatedAt)
      assert.ok(Number.isInteger(version.chars))
    }

    // A corrupt sidecar degrades to the same empty source.
    await writeFile(path.join(historyDir, '20260102-120000-000.json'), '{not json')
    const degraded = await listHistory(dir)
    assert.equal(degraded[0].source, '')

    // Restoring a legacy snapshot still works and labels the new body.
    const restored = await restoreHistory(dir, '20260101-120000-000')
    assert.equal(restored.markdown, 'legacy body\n')
    assert.equal(
      JSON.parse(await readFile(path.join(dir, 'summary-source.json'), 'utf8')).source,
      'restore',
    )
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('pruning removes the source sidecar together with its snapshot', async () => {
  const { dir, root } = await tempPaper()
  try {
    await writeSummary(dir, 'v0', { source: 'summary' })
    for (let index = 1; index <= HISTORY_LIMIT + 2; index += 1) {
      await writeSummary(dir, `v${index}`, { source: index % 2 === 0 ? 'manual' : 'revision' })
    }
    const historyDir = path.join(dir, 'summary-history')
    const names = await readdir(historyDir)
    const markdown = names.filter((name) => name.endsWith('.md'))
    const sidecars = names.filter((name) => name.endsWith('.json'))
    assert.equal(markdown.length, HISTORY_LIMIT)
    // Every surviving snapshot has exactly one sidecar; pruned snapshots leave
    // no orphaned `.json` behind.
    assert.equal(sidecars.length, HISTORY_LIMIT)
    const stamps = new Set(markdown.map((name) => name.slice(0, -3)))
    for (const sidecar of sidecars) {
      assert.ok(stamps.has(sidecar.slice(0, -5)), `orphan sidecar ${sidecar}`)
    }
    for (const version of await listHistory(dir)) {
      assert.ok(['manual', 'revision', 'summary'].includes(version.source), version.source)
    }
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('restoreHistory snapshots the current body and rejects path traversal', async () => {
  const { dir, root } = await tempPaper()
  try {
    await writeSummary(dir, 'old body')
    await writeSummary(dir, 'current body')
    const [newest] = await listHistory(dir)
    const restored = await restoreHistory(dir, newest.stamp)
    assert.equal(restored.markdown, 'old body\n')
    assert.equal(restored.version, summaryVersion('old body\n'))
    assert.match(restored.snapshot, /^\d{8}-\d{6}-\d{3}(-\d+)?$/)
    assert.equal(await readFile(path.join(dir, 'summary.md'), 'utf8'), 'old body\n')
    // The overwritten body was preserved as a new snapshot.
    assert.equal(
      await readFile(path.join(dir, 'summary-history', `${restored.snapshot}.md`), 'utf8'),
      'current body\n',
    )

    for (const bad of [
      '../../etc/passwd',
      '..\\..\\win.ini',
      '20260101-000000',
      '20260101-000000-00',
      '20260101-000000-000-',
      '2026-01-01-000000-000',
      '',
      undefined,
      'abc',
      '20260101-000000-000/../../x',
    ]) {
      await assert.rejects(() => restoreHistory(dir, bad), /无效的历史版本编号/, `stamp ${String(bad)}`)
    }
    // A well-formed stamp that is simply absent is a 404, not a silent overwrite.
    await assert.rejects(() => restoreHistory(dir, '20990101-000000-000'), /历史版本不存在/)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('annotations round-trip, get cleaned and are capped', async () => {
  const { dir, root } = await tempPaper()
  try {
    await writeSummary(dir, BODY)
    assert.deepEqual(await readAnnotations(dir), [])

    const written = await writeAnnotations(dir, [
      {
        id: 'a1',
        quote: '信道损耗',
        prefix: '讨论 ',
        suffix: ' 与',
        start: 40,
        end: 44,
        note: '这里的损耗指什么？',
        color: 'rose',
        status: 'open',
      },
      { id: 'a1', quote: '重复 id 被忽略' },
      { id: '', quote: '没有 id' },
      { id: 'a2' },
      'not an object',
      { id: 'a3', quote: 'x'.repeat(3000), note: 'y'.repeat(3000), color: 'nope', status: 'nope' },
    ])
    assert.equal(written.annotations.length, 2)
    const [first, third] = written.annotations
    assert.equal(first.id, 'a1')
    assert.equal(first.color, 'rose')
    assert.equal(first.status, 'open')
    assert.equal(first.revision, 0)
    assert.equal(third.quote.length, 2000)
    assert.equal(third.note.length, 2000)
    assert.equal(third.color, 'amber')
    assert.equal(third.status, 'open')

    const reloaded = await readAnnotations(dir)
    assert.deepEqual(reloaded, written.annotations)
    const raw = JSON.parse(await readFile(annotationsPath(dir), 'utf8'))
    assert.equal(raw.version, 1)
    assert.ok(raw.updatedAt)

    const many = Array.from({ length: 260 }, (_, index) => ({ id: `n${index}`, quote: `q${index}` }))
    assert.equal(normalizeAnnotations(many).length, 200)

    // Corrupt JSON is treated as "no annotations" instead of throwing.
    await writeFile(annotationsPath(dir), '{not json')
    assert.deepEqual(await readAnnotations(dir), [])
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('anchorAnnotations re-locates open quotes and marks missing ones orphan', async () => {
  const annotations = [
    // "信道损耗" also appears in the abstract; the stored prefix disambiguates.
    {
      id: 'keep',
      quote: '信道损耗',
      prefix: '正文第一段，讨论 ',
      note: '为什么',
      status: 'open',
      start: 0,
      end: 4,
    },
    { id: 'gone', quote: '这句话已经不存在了', note: '过时', status: 'open', start: 0, end: 1 },
    { id: 'done', quote: '旧引用', status: 'resolved', start: 3, end: 6 },
  ]
  const result = anchorAnnotations(BODY, annotations)
  assert.deepEqual(result.anchored, ['keep'])
  assert.deepEqual(result.orphans, ['gone'])

  const keep = result.annotations.find((item) => item.id === 'keep')
  assert.equal(keep.status, 'open')
  assert.equal(BODY.slice(keep.start, keep.end), '信道损耗')
  // The located occurrence is the bold one in section 1, not the abstract.
  assert.ok(BODY.indexOf('信道损耗') < keep.start)
  assert.ok(keep.prefix.endsWith('讨论 '))
  assert.ok(keep.suffix.startsWith(' 与'))
  assert.ok(keep.prefix.length <= 48)
  assert.ok(keep.suffix.length <= 48)

  const gone = result.annotations.find((item) => item.id === 'gone')
  assert.equal(gone.status, 'orphan')
  assert.equal(gone.reply, '原文已改动，无法定位')
  assert.equal(gone.quote, '这句话已经不存在了')

  // Resolved annotations keep their stored state.
  const done = result.annotations.find((item) => item.id === 'done')
  assert.equal(done.status, 'resolved')
  assert.equal(done.start, 3)

  // Without context the nearest occurrence to `start` wins.
  const shifted = BODY.replace('正文第一段', '正文第一段（新增）')
  const target = shifted.lastIndexOf('信道损耗')
  const ambiguous = anchorAnnotations(shifted, [
    { id: 'x', quote: '信道损耗', note: '', status: 'open', start: target, end: target + 4 },
  ])
  assert.deepEqual(ambiguous.anchored, ['x'])
  const anchoredX = ambiguous.annotations[0]
  assert.equal(anchoredX.start, target)

  // An empty body orphans the open annotations but leaves resolved ones alone.
  assert.deepEqual(anchorAnnotations('', annotations).orphans, ['keep', 'gone'])
  assert.deepEqual(anchorAnnotations(BODY, []), { annotations: [], anchored: [], orphans: [] })
})

test('figure helpers produce and validate safe file names', async () => {
  const { dir, root } = await tempPaper()
  try {
    assert.equal(figureFileName(7, 1), 'fig-p07-01.png')
    assert.equal(figureFileName('12', 3), 'fig-p12-03.png')
    assert.equal(figureFileName(1, 12), 'fig-p01-12.png')
    assert.throws(() => figureFileName(0, 1), /无效的页码/)
    assert.throws(() => figureFileName(1, 0), /无效的图片序号/)

    assert.equal(isFigureName('fig-p07-01.png'), true)
    assert.equal(isFigureName('img-20261105-182900-a1b2.png'), true)
    assert.equal(isFigureName('img-20261105-182900-a1b2.jpg'), true)
    for (const bad of [
      '../fig-p07-01.png',
      '..\\fig-p07-01.png',
      'fig-p7-1.png',
      'fig-p07-01.gif',
      'fig-p07-01.png.exe',
      '/etc/passwd',
      'C:\\x.png',
      '',
      null,
      undefined,
      'fig-p07-01.png\u0000',
    ]) {
      assert.equal(isFigureName(bad), false, `should reject ${String(bad)}`)
    }

    const saved = await saveFigure(dir, 'fig-p07-01.png', Buffer.from([0x89, 0x50, 0x4e, 0x47]))
    assert.equal(saved.name, 'fig-p07-01.png')
    assert.equal(saved.size, 4)
    assert.equal(await readFile(path.join(figureDir(dir), 'fig-p07-01.png')).then((buf) => buf.length), 4)
    assert.equal(figureDir(dir), path.join(dir, 'figures'))
    await assert.rejects(() => saveFigure(dir, '../evil.png', Buffer.from('x')), /无效的图片文件名/)
    await assert.rejects(() => saveFigure(dir, 'fig-p07-01.png', Buffer.alloc(0)), /图片内容为空/)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})
